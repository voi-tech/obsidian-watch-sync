export function localeForLanguage(language: string): UiLocale {
	return language.toLowerCase().startsWith('pl') ? 'pl' : 'en';
}

export function translate(locale: UiLocale, key: string, params: TranslationParams = {}): string {
	const template = translations[locale][key] ?? translations.en[key] ?? key;
	return template.replace(/\{(\w+)\}/g, (match, name: string) =>
		Object.hasOwn(params, name) ? String(params[name]) : match,
	);
}

export function t(key: string, params: TranslationParams = {}): string {
	return translate(localeForLanguage(getLanguage()), key, params);
}
